def generate_comparison_table(d_matrix, method_names, crisis_keys, summary):
    """Generate paper/tables/table_comparison.tex -- main comparison table.

    Columns: Method | Median d | Mean Rank | Category
    Sorted by median d descending.
    """
    from scipy import stats

    n_crises, n_methods = d_matrix.shape

    # Median d per method
    median_d = np.nanmedian(d_matrix, axis=0)

    # Mean ranks from summary if available, else compute
    if summary and "mean_ranks" in summary:
        rank_lookup = summary["mean_ranks"]
        mean_ranks = np.array([
            rank_lookup.get(m, float("nan")) for m in method_names
        ])
    else:
        d_clean = d_matrix.copy()
        for j in range(n_methods):
            mask = np.isnan(d_clean[:, j])
            d_clean[mask, j] = np.nanmedian(d_clean[:, j])
        ranks = np.zeros_like(d_clean)
        for i in range(n_crises):
            ranks[i] = stats.rankdata(-d_clean[i])
        mean_ranks = np.mean(ranks, axis=0)

    # Friedman stats
    friedman_chi = summary.get("friedman_chi_sq", float("nan")) if summary else float("nan")
    friedman_p = summary.get("friedman_p", float("nan")) if summary else float("nan")

    # Sort by median d descending
    order = np.argsort(-median_d)

    # Find best median d
    best_d = np.nanmax(median_d)

    lines = []
    lines.append(f"% Auto-generated by populate_paper.py")
    lines.append(f"% {n_methods} methods x {n_crises} crises")
    lines.append(f"% Friedman chi-sq = {friedman_chi:.2f}, p = {friedman_p:.2e}")
    lines.append("")
    lines.append(r"\begin{tabular}{lccl}")
    lines.append(r"\toprule")
    lines.append(r"Method & Median $d$ & Mean Rank & Category \\")
    lines.append(r"\midrule")

    for idx in order:
        name = LATEX_NAMES.get(method_names[idx], method_names[idx])
        cat = METHOD_CATEGORIES.get(method_names[idx], "?")
        d_val = median_d[idx]
        rank_val = mean_ranks[idx]

        # Bold the best method
        if abs(d_val - best_d) < 1e-6:
            d_str = r"\textbf{" + f"{d_val:.2f}" + "}"
        else:
            d_str = f"{d_val:.2f}"

        lines.append(f"{name:<25} & {d_str} & {rank_val:.1f} & {cat} \\\\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")

    return "\n".join(lines)


def generate_per_crisis_table(d_matrix, method_names, crisis_keys):
    """Generate paper/tables/table_per_crisis.tex -- per-crisis breakdown.

    Shows top geometric methods + RF + CUSUM across all crises.
    Bold entries where best geometric method beats RF.
    """
    # Select top methods to display
    display_methods = [
        "Reduced Purity",
        "Berry Phase Rate",
        "QFI Determinant",
        "Hamilton MS",
        "CUSUM",
    ]
    # Only include methods that exist in the results
    display_indices = []
    actual_names = []
    for m in display_methods:
        if m in method_names:
            display_indices.append(method_names.index(m))
            actual_names.append(m)

    if not display_indices:
        return "% No matching methods found for per-crisis table"

    # Short names for columns
    short = {
        "Reduced Purity": "Red. Pur.",
        "Berry Phase Rate": "Berry",
        "QFI Determinant": "QFI Det.",
        "Hamilton MS": "Ham. MS",
        "CUSUM": "CUSUM",
    }
    header_names = [short.get(n, n[:8]) for n in actual_names]

    # Identify geometric vs classical indices for bolding
    geo_methods = {"Reduced Purity", "Berry Phase Rate", "QFI Determinant"}
    geo_indices = [method_names.index(m) for m in geo_methods if m in method_names]
    rf_idx = method_names.index("Hamilton MS") if "Hamilton MS" in method_names else -1

    # Pretty crisis names
    crisis_pretty = {
        "1997_asia": "1997 Asia",
        "1998_ltcm": "1998 LTCM",
        "2000_dotcom": "2000 Dotcom",
        "2001_911": "2001 9/11",
        "2001911": "2001 9/11",
        "2007_quant": "2007 Quant",
        "2008_gfc": "2008 GFC",
        "2010_flash": "2010 Flash",
        "2011_euro": "2011 Euro",
        "2013_taper": "2013 Taper",
        "2015_china": "2015 China",
        "2016_brexit": "2016 Brexit",
        "2018_volmageddon": "2018 Volmag.",
        "2018_q4": "2018 Q4",
        "2019_repo": "2019 Repo",
        "2020_covid": "2020 COVID",
        "2021_meme": "2021 Meme",
        "2022_rates": "2022 Rates",
        "2023_svb": "2023 SVB",
        "2024_carry": "2024 Carry",
    }

    lines = []
    lines.append("% Auto-generated by populate_paper.py")
    lines.append("")
    lines.append(r"\begin{tabular}{l" + "c" * len(display_indices) + "}")
    lines.append(r"\toprule")
    lines.append("Crisis & " + " & ".join(header_names) + r" \\")
    lines.append(r"\midrule")

    for i, crisis in enumerate(crisis_keys):
        name = crisis_pretty.get(crisis, crisis)

        # Determine if best geometric beats RF for this crisis
        rf_d = d_matrix[i, rf_idx] if rf_idx >= 0 else -1
        geo_d_vals = [d_matrix[i, gi] for gi in geo_indices] if geo_indices else []
        best_geo_d = max(geo_d_vals) if geo_d_vals else -1
        best_geo_idx = geo_indices[np.argmax(geo_d_vals)] if geo_d_vals else -1

        vals = []
        for idx in display_indices:
            d_val = d_matrix[i, idx]
            if np.isnan(d_val):
                vals.append("--")
            elif (
                idx in geo_indices
                and idx == best_geo_idx
                and best_geo_d > rf_d
                and rf_idx >= 0
            ):
                vals.append(r"\textbf{" + f"{d_val:.2f}" + "}")
            else:
                vals.append(f"{d_val:.2f}")

        lines.append(f"{name} & " + " & ".join(vals) + r" \\")

    # Median row
    lines.append(r"\midrule")
    medians = []
    for idx in display_indices:
        med = np.nanmedian(d_matrix[:, idx])
        medians.append(f"{med:.2f}")
    lines.append("Median & " + " & ".join(medians) + r" \\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")

    # Win count annotation
    if rf_idx >= 0 and geo_indices:
        wins = 0
        for i in range(len(crisis_keys)):
            best_geo = max(d_matrix[i, gi] for gi in geo_indices)
            if best_geo > d_matrix[i, rf_idx]:
                wins += 1
        lines.append("")
        lines.append(f"% Best geometric exceeds RF on {wins}/{len(crisis_keys)} crises")

    return "\n".join(lines)


def generate_holdout_table(holdout_path):
    """Generate paper/tables/table_holdout.tex from holdout JSON.

    Columns: Method | 2022 Rates d | SVB d | Carry d | Mean d
    Top 15 methods, sorted by mean d, best per-crisis column bolded.
    """
    with open(holdout_path) as f:
        data = json.load(f)

    crises = ["2022_rates", "2023_svb", "2024_carry"]
    crisis_labels = ["Rates", "SVB", "Carry"]

    rows = []
    for method, crisis_data in data["per_method"].items():
        ds = [crisis_data.get(c, {}).get("d", float("nan")) for c in crises]
        mean_d = np.nanmean(ds)
        rows.append((method, ds, mean_d))

    rows.sort(key=lambda x: -x[2])

    # Find best d per crisis column
    best_per_col = []
    for col_idx in range(len(crises)):
        col_vals = [r[1][col_idx] for r in rows if not np.isnan(r[1][col_idx])]
        best_per_col.append(max(col_vals) if col_vals else 0)
    best_mean = rows[0][2] if rows else 0

    lines = []
    lines.append("% Auto-generated by populate_paper.py (holdout)")
    lines.append(f"% {len(data['per_method'])} methods, 3 holdout crises")
    lines.append(f"% Cutoff: {data['metadata']['cutoff_date']}")
    lines.append("")
    lines.append(r"\begin{tabular}{lcccc}")
    lines.append(r"\toprule")
    lines.append("Method & " + " & ".join(crisis_labels) + r" & Mean $d$ \\")
    lines.append(r"\midrule")

    for method, ds, mean_d in rows[:15]:
        name = LATEX_NAMES.get(method, method)
        vals = []
        for col_idx, d_val in enumerate(ds):
            if np.isnan(d_val):
                vals.append("--")
            elif abs(d_val - best_per_col[col_idx]) < 1e-6:
                vals.append(r"\textbf{" + f"{d_val:.2f}" + "}")
            else:
                vals.append(f"{d_val:.2f}")
        mean_str = (r"\textbf{" + f"{mean_d:.2f}" + "}") if abs(mean_d - best_mean) < 1e-6 else f"{mean_d:.2f}"
        lines.append(f"{name:<25} & " + " & ".join(vals) + f" & {mean_str}" + r" \\")

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")

    return "\n".join(lines)


def generate_lead_time_table(lead_time_path):
    """Generate paper/tables/table_lead_time.tex from lead time JSON.

    Columns: Method | Mean Lead (days) | Median Lead | Det. Rate (n/17) | Category
    All methods that detected >= 1 crisis, sorted by detection rate * mean lead.
    """
    with open(lead_time_path) as f:
        data = json.load(f)

    rows = []
    for method, stats in data["summary"].items():
        n_det = stats["n_detected"]
        n_tot = stats["n_total"]
        mean_lead = stats["mean_lead_time"]
        median_lead = stats["median_lead_time"]
        if n_det == 0:
            continue
        score = (n_det / n_tot) * (mean_lead or 0)
        rows.append((method, mean_lead or 0, median_lead or 0, n_det, n_tot, score))

    rows.sort(key=lambda x: -x[5])

    # Friedman stats from lead time JSON
    friedman = data.get("statistical_tests", {}).get("friedman", {})
    chi_sq = friedman.get("chi_sq", float("nan"))
    p_val = friedman.get("p_value", float("nan"))

    lines = []
    lines.append("% Auto-generated by populate_paper.py (lead time)")
    lines.append(f"% Friedman chi-sq = {chi_sq:.1f}, p = {p_val:.1e}")
    lines.append("")
    lines.append(r"\begin{tabular}{lccll}")
    lines.append(r"\toprule")
    lines.append(r"Method & Mean Lead & Median Lead & Det.\ Rate & Category \\")
    lines.append(r"\midrule")

    for method, mean_lead, median_lead, n_det, n_tot, score in rows:
        name = LATEX_NAMES.get(method, method)
        cat = METHOD_CATEGORIES.get(method, "?")
        det_str = f"{n_det}/{n_tot}"
        lines.append(
            f"{name:<25} & {mean_lead:.0f} & {median_lead:.0f} & {det_str} & {cat}" + r" \\"
        )

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")

    return "\n".join(lines)


def generate_fusion_table(fusion_path):
    """Generate paper/tables/table_fusion.tex from fusion results JSON.

    Columns: Method | Mean d | Median d | CV | Category
    Top 5 individuals + all 7 fusion methods, sorted by mean d.
    """
    with open(fusion_path) as f:
        data = json.load(f)

    aggregate = data["aggregate"]
    friedman = data.get("friedman", {})
    chi_sq = friedman.get("chi_sq", float("nan"))
    p_val = friedman.get("p_value", float("nan"))

    # Separate individuals and fusion methods
    individuals = [r for r in aggregate if r["category"] == "individual"]
    fusions = [r for r in aggregate if r["category"] != "individual"]

    # Top 5 individuals by mean d
    individuals.sort(key=lambda x: -x["mean_d"])
    top_individuals = individuals[:5]

    # All fusion methods sorted by mean d
    fusions.sort(key=lambda x: -x["mean_d"])

    rows = top_individuals + fusions

    # Category labels for fusion types
    cat_labels = {
        "individual": "Individual",
        "flat_fusion": "Flat Fusion",
        "hierarchical": "Hierarchical",
        "regime_adaptive": "Regime-Adaptive",
        "sprt": "SPRT",
    }

    lines = []
    lines.append("% Auto-generated by populate_paper.py (fusion)")
    lines.append(f"% Friedman chi-sq = {chi_sq:.2f}, p = {p_val:.4f}")
    lines.append("")
    lines.append(r"\begin{tabular}{lcccc}")
    lines.append(r"\toprule")
    lines.append(r"Method & Mean $d$ & Median $d$ & CV & Category \\")
    lines.append(r"\midrule")

    best_mean = max(r["mean_d"] for r in rows)
    added_rule = False

    for row in rows:
        if not added_rule and row["category"] != "individual":
            lines.append(r"\midrule")
            added_rule = True
        name = LATEX_NAMES.get(row["method"], row["method"])
        mean_d = row["mean_d"]
        median_d = row["median_d"]
        std_d = row["std_d"]
        cv = std_d / mean_d if mean_d > 0 else float("inf")
        cat = cat_labels.get(row["category"], row["category"])

        mean_str = f"{mean_d:.3f}"
        if abs(mean_d - best_mean) < 1e-6:
            mean_str = r"\textbf{" + mean_str + "}"

        lines.append(
            f"{name:<25} & {mean_str} & {median_d:.3f} & {cv:.2f} & {cat}" + r" \\"
        )

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")

    return "\n".join(lines)


def generate_fusion_holdout_table(holdout_path):
    """Generate paper/tables/table_fusion_holdout.tex from fusion holdout JSON.

    Shows top 3 fusion methods + Reduced Purity + Spectral Entropy.
    Columns: Method | per-crisis d values | Mean d.  Bold best per-column.
    """
    with open(holdout_path) as f:
        data = json.load(f)

    crises = data["metadata"]["crises"]
    crisis_labels = {
        "2021_meme": "Meme",
        "2022_rates": "Rates",
        "2023_svb": "SVB",
        "2024_carry": "Carry",
    }

    # Build per-method aggregates
    methods = {}
    for row in data["per_crisis"]:
        m = row["method"]
        if m not in methods:
            methods[m] = {"per_crisis": {}, "ds": []}
        methods[m]["per_crisis"][row["crisis"]] = row["d"]
        methods[m]["ds"].append(row["d"])

    # Select display methods: top 3 fusion + 2 key individuals
    fusion_names = [
        "Regime-Adaptive",
        "Hierarchical Rank",
        "Flat Rank Fusion",
    ]
    individual_names = [
        "Reduced Purity",
        "Spectral Entropy",
    ]
    display_methods = fusion_names + individual_names
    display_methods = [m for m in display_methods if m in methods]

    # Find best per column
    best_per_col = {}
    for c in crises:
        col_vals = [methods[m]["per_crisis"].get(c, float("nan"))
                    for m in display_methods
                    if not np.isnan(methods[m]["per_crisis"].get(c, float("nan")))]
        best_per_col[c] = max(col_vals) if col_vals else 0

    mean_ds = {m: np.mean(methods[m]["ds"]) for m in display_methods}
    best_mean = max(mean_ds.values())

    col_headers = [crisis_labels.get(c, c) for c in crises]

    lines = []
    lines.append("% Auto-generated by populate_paper.py (fusion holdout)")
    lines.append(f"% {len(crises)} holdout crises")
    lines.append("")
    lines.append(r"\begin{tabular}{l" + "c" * len(crises) + "c}")
    lines.append(r"\toprule")
    lines.append(
        "Method & " + " & ".join(col_headers) + r" & Mean $d$ \\"
    )
    lines.append(r"\midrule")

    added_rule = False
    for m in display_methods:
        if not added_rule and m in individual_names:
            lines.append(r"\midrule")
            added_rule = True
        name = LATEX_NAMES.get(m, m)
        vals = []
        for c in crises:
            d_val = methods[m]["per_crisis"].get(c, float("nan"))
            if np.isnan(d_val):
                vals.append("--")
            elif abs(d_val - best_per_col[c]) < 1e-6:
                vals.append(r"\textbf{" + f"{d_val:.2f}" + "}")
            else:
                vals.append(f"{d_val:.2f}")
        mean_d = mean_ds[m]
        mean_str = f"{mean_d:.3f}"
        if abs(mean_d - best_mean) < 1e-3:
            mean_str = r"\textbf{" + mean_str + "}"
        lines.append(
            f"{name:<25} & " + " & ".join(vals) + f" & {mean_str}" + r" \\"
        )

    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")

    return "\n".join(lines)


