"""
Paper population pipeline: JSON results -> LaTeX table fragments -> PDF.

Reads the latest experiment results JSON, generates .tex table fragments
in paper/tables/, and compiles the paper.

Usage:
    python paper/populate_paper.py                      # auto-find latest JSON
    python paper/populate_paper.py --json path/to.json  # specific JSON
    python paper/populate_paper.py --compile            # also run pdflatex
"""

import argparse
import glob
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

# ---------------------------------------------------------------------------
# Resolve repo root so we can import from experiments/
# ---------------------------------------------------------------------------
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from experiments.generate_paper_tables import (
    METHOD_CATEGORIES,
    LATEX_NAMES,
    build_d_matrix,
)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
TABLES_DIR = REPO_ROOT / "paper" / "tables"
FIGURES_SRC = REPO_ROOT / "experiments" / "outputs" / "regime_detection"
FIGURES_DST = REPO_ROOT / "paper" / "figures"
PAPER_DIR = REPO_ROOT / "paper"
TEX_MAIN = PAPER_DIR / "qcml_geometric_sde.tex"

RESULTS_DIR = REPO_ROOT / "experiments" / "outputs" / "regime_detection"


def find_latest_json() -> Path:
    """Find the most recent comparison_*.json or causal_comparison_*.json."""
    patterns = [
        str(RESULTS_DIR / "causal_comparison_*.json"),
        str(RESULTS_DIR / "comparison_*.json"),
    ]
    candidates = []
    for pat in patterns:
        candidates.extend(glob.glob(pat))

    if not candidates:
        raise FileNotFoundError(
            f"No comparison JSON files found in {RESULTS_DIR}. "
            "Run experiments/regime_comparison.py first."
        )

    # Sort by modification time (newest first)
    candidates.sort(key=os.path.getmtime, reverse=True)
    return Path(candidates[0])


