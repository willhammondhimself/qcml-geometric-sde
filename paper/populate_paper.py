def copy_figures():
    """Copy publication figures from experiment outputs to paper/figures/."""
    FIGURES_DST.mkdir(parents=True, exist_ok=True)

    # Patterns of figures to copy
    figure_globs = [
        str(FIGURES_SRC / "*.pdf"),
        str(FIGURES_SRC / "*.png"),
        str(REPO_ROOT / "experiments" / "outputs" / "regime_detection" / "figures" / "*.pdf"),
        str(REPO_ROOT / "experiments" / "outputs" / "regime_detection" / "figures" / "*.png"),
    ]

    copied = 0
    for pat in figure_globs:
        for src_path in glob.glob(pat):
            src = Path(src_path)
            dst = FIGURES_DST / src.name
            if not dst.exists() or src.stat().st_mtime > dst.stat().st_mtime:
                shutil.copy2(src, dst)
                copied += 1

    return copied


