def compile_paper():
    """Compile the paper with pdflatex (3 passes) + bibtex if .bib exists."""
    if not TEX_MAIN.exists():
        print(f"ERROR: {TEX_MAIN} not found")
        return False

    tex_stem = TEX_MAIN.stem

    # Check for .bib file
    bib_file = PAPER_DIR / f"{tex_stem}.bib"
    use_bibtex = bib_file.exists()

    commands = []
    # Pass 1
    commands.append(
        ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex_stem]
    )
    # Bibtex (if .bib exists)
    if use_bibtex:
        commands.append(["bibtex", tex_stem])
    # Pass 2
    commands.append(
        ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex_stem]
    )
    # Pass 3
    commands.append(
        ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex_stem]
    )

    for cmd in commands:
        print(f"  Running: {' '.join(cmd)}")
        result = subprocess.run(
            cmd,
            cwd=str(PAPER_DIR),
            capture_output=True,
            text=True,
            timeout=120,
        )
        if result.returncode != 0:
            # pdflatex often returns non-zero on warnings; check for actual errors
            if "Fatal error" in result.stdout or "Emergency stop" in result.stdout:
                print(f"  FAILED: {cmd[0]}")
                # Print last 20 lines of output for debugging
                out_lines = result.stdout.strip().split("\n")
                for line in out_lines[-20:]:
                    print(f"    {line}")
                return False

    pdf_path = PAPER_DIR / f"{tex_stem}.pdf"
    if pdf_path.exists():
        size_mb = pdf_path.stat().st_size / (1024 * 1024)
        print(f"  PDF generated: {pdf_path} ({size_mb:.1f} MB)")
        return True
    else:
        print("  WARNING: PDF not found after compilation")
        return False


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="Paper population pipeline: JSON results -> LaTeX tables -> PDF"
    )
    parser.add_argument(
        "--json",
        type=str,
        default=None,
        help="Path to comparison results JSON (default: auto-find latest)",
    )
    parser.add_argument(
        "--compile",
        action="store_true",
        help="Compile the paper with pdflatex after generating tables",
    )
    parser.add_argument(
        "--copy-figures",
        action="store_true",
        help="Copy figures from experiment outputs to paper/figures/",
    )
    args = parser.parse_args()

    # --- Step 1: Find JSON ---
    if args.json:
        json_path = Path(args.json)
        if not json_path.exists():
            print(f"ERROR: {json_path} does not exist")
            sys.exit(1)
    else:
        json_path = find_latest_json()

    print(f"Loading results from: {json_path.name}")

    with open(json_path) as f:
        data = json.load(f)

    results_dict = data["results"]
    summary = data.get("summary", {})

    # --- Step 2: Build matrix ---
    d_matrix, method_names, crisis_keys = build_d_matrix(results_dict)
    n_methods = len(method_names)
    n_crises = len(crisis_keys)
    print(f"  {n_methods} methods x {n_crises} crises")

    # --- Step 3: Generate table fragments ---
    TABLES_DIR.mkdir(parents=True, exist_ok=True)

    # Table: main comparison
    comparison_tex = generate_comparison_table(d_matrix, method_names, crisis_keys, summary)
    comparison_path = TABLES_DIR / "table_comparison.tex"
    comparison_path.write_text(comparison_tex)
    print(f"  Written: {comparison_path.relative_to(REPO_ROOT)}")

    # Table: per-crisis breakdown
    per_crisis_tex = generate_per_crisis_table(d_matrix, method_names, crisis_keys)
    per_crisis_path = TABLES_DIR / "table_per_crisis.tex"
    per_crisis_path.write_text(per_crisis_tex)
    print(f"  Written: {per_crisis_path.relative_to(REPO_ROOT)}")

    # Table: holdout (find latest)
    holdout_dir = REPO_ROOT / "experiments" / "outputs" / "holdout"
    holdout_candidates = sorted(glob.glob(str(holdout_dir / "holdout_*.json")))
    if holdout_candidates:
        holdout_path = Path(holdout_candidates[-1])
        holdout_tex = generate_holdout_table(holdout_path)
        holdout_out = TABLES_DIR / "table_holdout.tex"
        holdout_out.write_text(holdout_tex)
        print(f"  Written: {holdout_out.relative_to(REPO_ROOT)} (from {holdout_path.name})")
    else:
        print("  SKIP: no holdout JSON found")

    # Table: lead time (find latest)
    lead_time_dir = REPO_ROOT / "experiments" / "outputs" / "lead_time"
    lead_time_candidates = sorted(glob.glob(str(lead_time_dir / "lead_time_*.json")))
    if lead_time_candidates:
        lead_time_path = Path(lead_time_candidates[-1])
        lead_time_tex = generate_lead_time_table(lead_time_path)
        lead_time_out = TABLES_DIR / "table_lead_time.tex"
        lead_time_out.write_text(lead_time_tex)
        print(f"  Written: {lead_time_out.relative_to(REPO_ROOT)} (from {lead_time_path.name})")
    else:
        print("  SKIP: no lead time JSON found")

    # Table: fusion (find latest)
    fusion_candidates = sorted(glob.glob(str(FUSION_DIR / "fusion_results_*.json")))
    # Separate full vs holdout by checking metadata preset
    fusion_full_path = None
    fusion_holdout_path = None
    for fc in fusion_candidates:
        with open(fc) as f:
            meta = json.load(f).get("metadata", {})
        if meta.get("preset") == "holdout":
            fusion_holdout_path = Path(fc)
        else:
            fusion_full_path = Path(fc)

    if fusion_full_path:
        fusion_tex = generate_fusion_table(fusion_full_path)
        fusion_out = TABLES_DIR / "table_fusion.tex"
        fusion_out.write_text(fusion_tex)
        print(f"  Written: {fusion_out.relative_to(REPO_ROOT)} (from {fusion_full_path.name})")
    else:
        print("  SKIP: no fusion full JSON found")

    if fusion_holdout_path:
        fusion_holdout_tex = generate_fusion_holdout_table(fusion_holdout_path)
        fusion_holdout_out = TABLES_DIR / "table_fusion_holdout.tex"
        fusion_holdout_out.write_text(fusion_holdout_tex)
        print(
            f"  Written: {fusion_holdout_out.relative_to(REPO_ROOT)}"
            f" (from {fusion_holdout_path.name})"
        )
    else:
        print("  SKIP: no fusion holdout JSON found")

    # Print summary to stdout
    median_d = np.nanmedian(d_matrix, axis=0)
    order = np.argsort(-median_d)
    print("\n  Method rankings (by median d):")
    for rank, idx in enumerate(order, 1):
        cat = METHOD_CATEGORIES.get(method_names[idx], "?")
        print(f"    {rank:2d}. {method_names[idx]:<25} d={median_d[idx]:.3f}  [{cat}]")

    # Friedman stats
    chi_sq = summary.get("friedman_chi_sq", float("nan"))
    p_val = summary.get("friedman_p", float("nan"))
    print(f"\n  Friedman chi-sq = {chi_sq:.2f}, p = {p_val:.2e}")

    # --- Step 3b: Copy observatory heatmap if available ---
    observatory_heatmap = (
        REPO_ROOT / "experiments" / "outputs" / "observatory" / "orthogonality_heatmap.pdf"
    )
    if observatory_heatmap.exists():
        FIGURES_DST.mkdir(parents=True, exist_ok=True)
        dst = FIGURES_DST / "orthogonality_heatmap.pdf"
        shutil.copy2(observatory_heatmap, dst)
        print(f"  Copied observatory heatmap to {dst.relative_to(REPO_ROOT)}")

    # --- Step 4: Copy figures ---
    if args.copy_figures:
        n_copied = copy_figures()
        print(f"\n  Copied {n_copied} figure(s) to paper/figures/")

    # --- Step 5: Compile ---
    if args.compile:
        print("\nCompiling paper...")
        success = compile_paper()
        if not success:
            print("Compilation failed. Check paper/*.log for details.")
            sys.exit(1)
        print("Compilation complete.")

    print("\nDone.")


if __name__ == "__main__":
    main()
